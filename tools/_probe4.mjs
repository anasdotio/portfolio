import { chromium } from "playwright";
import fs from "node:fs";
import { decode } from "./pngtool.mjs";
const browser = await chromium.launch();
const page = await browser.newPage({viewport:{width:1400,height:1400}});
const b64 = fs.readFileSync("src/assets/profile-new.jpg").toString("base64");
await page.setContent(`<body style="margin:0"><img id="i" src="data:image/jpeg;base64,${b64}" style="display:block;width:1254px;height:1254px"></body>`);
await page.waitForTimeout(300);
const shot = await page.locator("#i").screenshot({type:"png"});
await browser.close();
fs.writeFileSync("shots/raw-src.png", shot);
const img = decode(shot);
console.log("channels", img.channels);
const at=(x,y)=>{const i=(y*img.width+x)*img.channels;return [img.data[i],img.data[i+1],img.data[i+2]];};
const luma=(p)=>0.299*p[0]+0.587*p[1]+0.114*p[2];
const sat=(p)=>Math.max(...p)-Math.min(...p);
const show=(label,x,y)=>{const p=at(x,y);console.log(label.padEnd(16),x,y,p,"luma",luma(p).toFixed(0),"sat",sat(p));};
console.log("--- backdrop ---");
show("bg top-left",20,20); show("bg top-mid",627,20); show("bg left",20,600); show("bg right",1233,600);
console.log("--- hair sheen (suspected bridge) ---");
for(const y of [80,100,120,150]) show("hair",627,y);
console.log("--- forehead highlights ---");
for(const y of [230,250,270]) show("forehead",607,y);
console.log("--- nose bridge ---");
show("nose",627,300); show("nose",640,320);
console.log("--- cheeks ---");
show("cheekL",480,330); show("cheekR",760,330);
console.log("--- typical skin ---");
show("jaw",600,430); show("ear",800,330);
